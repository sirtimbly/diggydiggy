// Sixteen-pixel originals: solid clusters and hard edges match the diggers.
// Each sprite has its own silhouette; no smoothing or external image requests.
const ink = "#342b2a", cream = "#f7e9c6";
function sprite(palette, paint) {
  const pixels = Array.from({ length: 16 }, () => Array(16).fill(null));
  const rect = (x, y, width, height, color) => {
    for (let row = y; row < y + height; row++) for (let column = x; column < x + width; column++)
      if (row >= 0 && row < 16 && column >= 0 && column < 16) pixels[row][column] = color;
  };
  const dots = (points, color) => points.forEach(([x, y]) => rect(x, y, 1, 1, color));
  paint(rect, dots);
  return { palette: { o: ink, c: cream, ...palette }, pixels };
}

