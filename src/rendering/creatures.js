export function creaturePaths(id) {
  const { pixels, palette } = CREATURE_SPRITES[id] ?? CREATURE_SPRITES.mole;
  const paths = new Map();
  pixels.forEach((row, y) => row.forEach((pixel, x) => {
    if (pixel) paths.set(palette[pixel], (paths.get(palette[pixel]) ?? "") + `M${x} ${y}h1v1h-1z`);
  }));
  return [...paths].map(([fill, d]) => ({ fill, d }));
}
